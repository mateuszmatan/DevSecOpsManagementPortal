CREATE TABLE DSO_PIPELINE_REPORT (
    ID                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PIPELINE_ID         NUMBER(19),
    PIPELINE_KEY        VARCHAR2(255),
    JOB_NAME            VARCHAR2(255),
    BUILD_NUMBER        NUMBER(19),
    RESULT              VARCHAR2(50),
    BRANCH              VARCHAR2(255),
    COMMIT_HASH         VARCHAR2(255),
    DURATION_SECONDS    NUMBER(19),
    FINISHED_AT         TIMESTAMP       NOT NULL,
    STAGES_TOTAL        NUMBER(10),
    PASSED              NUMBER(10),
    WARNED              NUMBER(10),
    FAILED              NUMBER(10),
    BLOCKED             NUMBER(10),
    SKIPPED             NUMBER(10),
    REPORT_HTML         CLOB
);
CREATE INDEX IX_DSO_REPORT_PIPELINE ON DSO_PIPELINE_REPORT (PIPELINE_ID, FINISHED_AT DESC);
CREATE INDEX IX_DSO_REPORT_KEY ON DSO_PIPELINE_REPORT (PIPELINE_KEY, FINISHED_AT DESC);
