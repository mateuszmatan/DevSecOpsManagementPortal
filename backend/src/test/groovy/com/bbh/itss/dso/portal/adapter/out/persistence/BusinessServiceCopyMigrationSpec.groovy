package com.bbh.itss.dso.portal.adapter.out.persistence

import com.bbh.itss.dso.portal.domain.catalog.Product
import com.bbh.itss.dso.portal.domain.catalog.ServiceDraft
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase
import org.springframework.context.annotation.Import
import org.springframework.transaction.annotation.Transactional

import static com.bbh.itss.dso.portal.support.CatalogFixtures.details
import static com.bbh.itss.dso.portal.support.Fixtures.settings
import static org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase.Replace.NONE
import static org.springframework.transaction.annotation.Propagation.NOT_SUPPORTED

@DataJpaTest(properties = [
        'spring.datasource.url=jdbc:h2:file:./build/business-service-migration/db;MODE=Oracle;DEFAULT_NULL_ORDERING=HIGH',
        'spring.datasource.username=sa',
        'spring.liquibase.enabled=false'])
@AutoConfigureTestDatabase(replace = NONE)
@Transactional(propagation = NOT_SUPPORTED)
@Import(ProductPersistenceAdapter)
class BusinessServiceCopyMigrationSpec extends MigrationSpecification {

    // what the build of c9c2f47 added to 011 and 028
    static final List<String> COPY = [
            '''CREATE TABLE DSO_BUSINESS_SERVICE (
                   ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR2(100) NOT NULL,
                   CREATED_AT TIMESTAMP NOT NULL, UPDATED_AT TIMESTAMP NOT NULL, VERSION NUMBER(19) DEFAULT 0 NOT NULL,
                   CONSTRAINT PK_DSO_BUSINESS_SERVICE PRIMARY KEY (ID), CONSTRAINT UK_DSO_BS_NAME UNIQUE (NAME))''',
            '''INSERT INTO DSO_BUSINESS_SERVICE (NAME, CREATED_AT, UPDATED_AT)
                   SELECT NAME, CREATED_AT, UPDATED_AT FROM DSO_DEPARTMENT''',
            'ALTER TABLE DSO_PRODUCT ADD (BUSINESS_SERVICE_ID NUMBER(19))',
            'CREATE INDEX IX_DSO_PRODUCT_BS ON DSO_PRODUCT (BUSINESS_SERVICE_ID)',
            '''ALTER TABLE DSO_PRODUCT ADD CONSTRAINT FK_DSO_PRODUCT_BS FOREIGN KEY (BUSINESS_SERVICE_ID)
                   REFERENCES DSO_BUSINESS_SERVICE (ID)''',
            '''UPDATE DSO_PRODUCT p SET BUSINESS_SERVICE_ID =
                   (SELECT b.ID FROM DSO_BUSINESS_SERVICE b JOIN DSO_DEPARTMENT d ON d.NAME = b.NAME WHERE d.ID = p.DEPARTMENT_ID)''',
            'ALTER TABLE DSO_ACTION_LOG ADD (BUSINESS_SERVICE_NAME VARCHAR2(200))',
            'UPDATE DSO_ACTION_LOG SET BUSINESS_SERVICE_NAME = DEPARTMENT_NAME']

    @Autowired
    ProductPersistenceAdapter products

    @Override
    protected String changelogFile() {
        'db/changelog/db.changelog-master.yaml'
    }

    def "029 drops the copy of the departments that the build of c9c2f47 left, and keeps the products and their departments"() {
        given:
        jdbc.execute('DROP ALL OBJECTS')
        liquibase.update('')
        def saved = inTransaction {
            products.save(Product.create(details(), [new ServiceDraft(null, 'gui', null, settings())], products))
        }
        COPY.each { jdbc.execute(it) }
        jdbc.update("DELETE FROM DATABASECHANGELOG WHERE ID LIKE '029-%'")
        reopen()

        expect:
        jdbc.queryForObject('SELECT COUNT(*) FROM DSO_PRODUCT WHERE BUSINESS_SERVICE_ID IS NOT NULL', Integer) > 0

        when:
        liquibase.update('')

        then:
        !('DSO_BUSINESS_SERVICE' in tables())
        !('BUSINESS_SERVICE_ID' in columns('DSO_PRODUCT'))
        !('BUSINESS_SERVICE_NAME' in columns('DSO_ACTION_LOG'))
        objects('INDEXES', 'INDEX_NAME', 'IX_DSO_PRODUCT_BS') == 0
        objects('TABLE_CONSTRAINTS', 'CONSTRAINT_NAME', 'FK_DSO_PRODUCT_BS') == 0
        inTransaction { products.load(saved.id()).get().details() } == details()
        ran029() == ['EXECUTED'] * 3
    }

    def "029 changes nothing on a database that never had the copy, and rolls back without restoring it"() {
        given:
        jdbc.execute('DROP ALL OBJECTS')

        when:
        liquibase.update('')

        then:
        ran029() == ['MARK_RAN'] * 3
        jdbc.queryForList('SELECT NAME FROM DSO_DEPARTMENT ORDER BY ID', String) ==
                ['AI Lab', 'Capital Partners', 'Corporate Technology', 'Custody', 'Fund Services']

        when:
        rollBackSince('029-')

        then:
        ran029() == []
        !('DSO_BUSINESS_SERVICE' in tables())
    }

    private int objects(String view, String column, String name) {
        jdbc.queryForObject("SELECT COUNT(*) FROM INFORMATION_SCHEMA.$view WHERE $column = ?", Integer, name)
    }

    private List<String> ran029() {
        jdbc.queryForList("SELECT EXECTYPE FROM DATABASECHANGELOG WHERE ID LIKE '029-%' ORDER BY ORDEREXECUTED", String)
    }
}
